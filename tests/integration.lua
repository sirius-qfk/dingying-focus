local Mock = assert(loadfile("tests/mock.lua"))()
local G = {}
for _, file in ipairs({ "Core.lua", "Runtime.lua", "Model.lua", "Bindings.lua", "Journal.lua", "Integrations/EUI/Compatibility.lua", "Integrations/EUI/ActionBars.lua", "Integrations/EUI/Cooldowns.lua", "Integrations/EUI/Elements.lua", "Store.lua", "Engine.lua", "UI/Editor.lua", "UI/Regions.lua", "Integrations/EUI/NativeControls.lua", "Integrations/EUI/SettingsHost.lua", "UI/EUIBridge.lua", "Bootstrap.lua" }) do
    assert(loadfile(file))("EllesmereUIGradient", G)
end
local E = G.Engine
local passed = 0
local function test(name, fn)
    local ok, err = pcall(fn)
    assert(ok, name .. ": " .. tostring(err))
    passed = passed + 1; print("ok - " .. name)
end

test("initialization is read-only until user edits", function()
    E:Init({}); G.Adapter.InstallHooks(); G.Bridge:Install(); Mock.Flush()
    assert(Mock.ab.db.profile.bars.MainBar.buttonWidth == 24)
end)
test("editor is embedded in the EUI host", function()
    G.Bridge:Open(); Mock.Flush()
    assert(G.Editor.panel:GetParent() == EllesmereUI:GetMainFrame())
    assert(E.editing and #G.Editor.cells == 12)
end)
test("one tier resizes multiple bound groups", function()
    E:Change("icon", "t3", nil, 32); Mock.Flush()
    assert(Mock.ab.db.profile.bars.Bar2.buttonWidth == 32)
    assert(Mock.ab.db.profile.bars.Bar3.buttonWidth == 32)
    assert(Mock.ab.db.profile.bars.MainBar.buttonWidth == 36)
    assert(not E.entry.enabled and #E.targets == 5)
end)
test("cancel restores numbers and original frame points", function()
    assert(E:Cancel()); Mock.Flush()
    assert(Mock.ab.db.profile.bars.MainBar.buttonWidth == 24)
    local _, _, _, x, y = EABBar_MainBar:GetPoint()
    assert(x == 100 and y == 80)
    assert(not E.entry.enabled and next(E.entry.applied.leases) == nil)
end)
test("apply persists semantic tiers", function()
    G.Bridge:Open(); E:Change("text", "t2", nil, 15); Mock.Flush(); assert(E:Apply()); Mock.Flush()
    assert(E.entry.settings.text.t2 == 15 and E.entry.enabled)
    assert(Mock.ab.db.profile.bars.MainBar.keybindFontSize == 15)
    assert(Mock.nsCD.GetBarData("utility").cooldownFontSize == 15)
end)
test("region changes reposition bound groups", function()
    E:Change("regions", "t1", "height", 400); Mock.Flush()
    local _, _, _, _, y = Mock.nsCD.frames.cooldowns:GetPoint(); assert(y == -200)
end)
test("cancel after apply keeps saved values", function()
    assert(E:Cancel()); Mock.Flush()
    assert(E.entry.enabled and Mock.ab.db.profile.bars.MainBar.keybindFontSize == 15)
    local _, _, _, _, y = Mock.nsCD.frames.cooldowns:GetPoint(); assert(y == -math.floor(1080*0.32)/2)
end)
test("invalid drafts do not mutate live UI", function()
    G.Bridge:Open(); local prior = Mock.ab.db.profile.bars.MainBar.buttonWidth
    E:Change("icon", "t2", nil, 999); Mock.Flush()
    assert(E.error and Mock.ab.db.profile.bars.MainBar.buttonWidth == prior)
    assert(not E:Apply()); assert(E:Cancel()); Mock.Flush()
end)
test("layout failure rolls back the entire transaction", function()
    G.Bridge:Open(); local before = G.Copy(Mock.ab.db.profile)
    Mock.refreshError = "Bar2"
    E:Change("icon", "t2", nil, 40); Mock.Flush()
    Mock.refreshError = nil
    assert(E.error and G.Equal(before, Mock.ab.db.profile))
    assert(E:Cancel()); Mock.Flush()
end)
test("combat queues the latest preview without resizing", function()
    G.Bridge:Open(); Mock.combat = true; local prior = Mock.writes
    E:Change("icon", "t2", nil, 37); E:Change("icon", "t2", nil, 38); Mock.Flush()
    assert(Mock.writes == prior)
    Mock.combat = false; E:Schedule("PLAYER_REGEN_ENABLED"); Mock.Flush()
    assert(Mock.ab.db.profile.bars.MainBar.buttonWidth == 38)
    E:Cancel(); Mock.Flush()
end)
test("blocked targets retain native layout", function()
    E:Restore(); Mock.Flush(); Mock.anchored = "MainBar"
    G.Bridge:Open(); E:Change("icon", "t2", nil, 40); Mock.Flush()
    assert(Mock.ab.db.profile.bars.MainBar.buttonWidth == 24)
    assert(E.status["action.MainBar"]:find("锚定"))
    E:Cancel(); Mock.Flush(); Mock.anchored = nil
end)
test("host refresh hooks do not create an infinite resize loop", function()
    G.Bridge:Open(); assert(E:Apply()); Mock.Flush()
    Mock.ab:ApplyButtonSizeForBar("MainBar"); Mock.Flush()
    assert(E.entry.enabled)
end)
test("managed slider displays tier, not a second editable value", function()
    local e = EllesmereUI
    e._buildingModule = "EllesmereUIActionBars"
    e._buildingSelector = { key = "MainBar" }
    local row = e.Widgets:DualRow(CreateFrame("Frame", nil, e.host), 0, { type = "slider", text = "Icon Size" })
    assert(G.NativeControls.slots[row._leftRegion])
    G.Bridge:RefreshSlots()
    assert(not row._leftRegion._control:IsShown())
    assert(G.NativeControls.slots[row._leftRegion].overlay:IsShown())
    E:Restore(); Mock.Flush(); assert(row._leftRegion._control:IsShown())
end)
test("later external writes survive restore", function()
    G.Bridge:Open(); assert(E:Apply()); Mock.Flush()
    Mock.ab.db.profile.bars.MainBar.buttonWidth = 77
    E:Restore(); Mock.Flush()
    assert(Mock.ab.db.profile.bars.MainBar.buttonWidth == 77)
    Mock.ab.db.profile.bars.MainBar.buttonWidth = 24
end)
test("profile change cancels stale draft and isolates settings", function()
    G.Bridge:Open(); E:Change("text", "t1", nil, 20); Mock.Flush()
    local old = E.context
    EllesmereUI.SwitchProfile("Second"); Mock.Flush()
    assert(E.context ~= old and not E.editing)
    assert(E.entry.settings.text.t1 == 16 and not E.entry.enabled)
end)
test("unknown EUI version refuses writes", function()
    Mock.version = "99.0"; local prior = Mock.writes
    assert(not G.Adapter.Probe()); assert(not E:Run(G.Model.Defaults()))
    assert(Mock.writes == prior); Mock.version = "9.3"
end)
test("future saved schema is not silently overwritten", function()
    local original = E.db; E:Init({ schema = 100, sentinel = true })
    assert(E.blocked and E.db == original)
end)
print("Integration contract tests passed: " .. passed .. " (not in-game verification)")
