local G = {}
for _, file in ipairs({ "Core.lua", "Model.lua", "Bindings.lua", "Journal.lua" }) do assert(loadfile(file))("EllesmereUIGradient", G) end
local passed = 0
local function test(name, fn)
    local ok, err = pcall(fn)
    assert(ok, name .. ": " .. tostring(err))
    passed = passed + 1
    print("ok - " .. name)
end

test("defaults validate", function() assert(G.Model.Validate(G.Model.Defaults(), 1920, 1080)) end)
test("viewport-aware defaults", function() assert(G.Model.Validate(G.Model.Defaults(1280, 720), 1280, 720)) end)
test("independent typography and icon tiers", function()
    local s = G.Model.Defaults(); s.text.t1, s.text.t3 = 8, 30
    assert(G.Model.Validate(s)); assert(s.icon.t1 == 42)
end)
test("NaN rejected", function() local s = G.Model.Defaults(); s.text.t1 = 0/0; assert(not G.Model.Validate(s)) end)
test("infinity rejected", function() local s = G.Model.Defaults(); s.icon.t1 = math.huge; assert(not G.Model.Validate(s)) end)
test("fractional size rejected", function() local s = G.Model.Defaults(); s.text.t2 = 12.5; assert(not G.Model.Validate(s)) end)
test("out of range size rejected", function() local s = G.Model.Defaults(); s.icon.t1 = 1; assert(not G.Model.Validate(s)) end)
test("missing tier rejected", function() local s = G.Model.Defaults(); s.text.t2 = nil; assert(not G.Model.Validate(s)) end)
test("missing region rejected", function() local s = G.Model.Defaults(); s.regions.t2 = nil; assert(not G.Model.Validate(s)) end)
test("non-nested regions rejected", function() local s = G.Model.Defaults(); s.regions.t2.width = s.regions.t1.width; assert(not G.Model.Validate(s)) end)
test("off-screen regions rejected", function() assert(not G.Model.Validate(G.Model.Defaults(), 600, 400)) end)
test("settings are not mutated by plan", function()
    local s = G.Model.Defaults(); local before = G.Copy(s)
    local p = assert(G.Model.Plan(s, G.Bindings)); assert(#p == 5); assert(G.Equal(before, s))
end)
test("binding changes do not change user settings", function()
    local s = G.Model.Defaults(); local b = G.Copy(G.Bindings)
    b[1].icon = "t1"; assert(G.Model.Plan(s, b)[1].icon == 42); assert(s.icon.t2 == 36)
end)
test("unknown binding tier rejected", function() local b = G.Copy(G.Bindings); b[1].icon = "bad"; assert(not G.Model.Plan(G.Model.Defaults(), b)) end)
test("region bottom anchor", function()
    local s = G.Model.Defaults(); local p = assert(G.Model.Position(G.Bindings[4], s, { width = 400, height = 42 }))
    assert(p.point == "BOTTOM" and p.y == -s.regions.t1.height/2)
end)
test("lane positions do not depend on smaller secondary icons", function()
    local p = assert(G.Model.Position(G.Bindings[3], G.Model.Defaults(), { width = 400, height = 30 }, 36))
    assert(p.y == -math.floor(1080*0.88)/2 + 2*44)
end)
test("oversized group rejected", function() assert(not G.Model.Position(G.Bindings[4], G.Model.Defaults(), { width = 5000, height = 40 })) end)
test("nil original restored", function()
    local state = {}; local j = G.Journal.New(); j:Begin(); assert(j:Write("a", state, "value", 42)); j:Commit()
    assert(state.value == 42); assert(#j:Restore() == 0); assert(state.value == nil)
end)
test("false original restored", function()
    local state = { value = false }; local j = G.Journal.New(); j:Begin(); j:Write("a", state, "value", true); j:Commit(); j:Restore(); assert(state.value == false)
end)
test("rollback preserves previous projection and original baseline", function()
    local state = { value = 10 }; local j = G.Journal.New(); j:Begin(); j:Write("a", state, "value", 20); j:Commit()
    j:Begin(); j:Write("a", state, "value", 30); j:Rollback(); assert(state.value == 20)
    j:Restore(); assert(state.value == 10)
end)
test("external writes never overwritten", function()
    local state = { value = 10 }; local j = G.Journal.New(); j:Begin(); j:Write("a", state, "value", 20); j:Commit()
    state.value = 99; j:Begin(); assert(not j:Write("a", state, "value", 30)); j:Rollback()
    assert(#j:Restore() == 1 and state.value == 99)
end)
test("restoration data survives serialization shape", function()
    local state = { position = { x = 1 } }; local saved = {}; local j = G.Journal.New(saved)
    j:Begin(); j:Write("p", state, "position", { x = 20 }); j:Commit()
    local afterReload = G.Journal.New(G.Copy(saved)); afterReload:Restore(function() return { object = state, key = "position" } end)
    assert(state.position.x == 1)
end)
test("overlapping target bounds are rejected", function()
    local function target(x, y) return { binding = { label = "test" }, position = { x = x, y = y }, extent = { width = 100, height = 40 } } end
    assert(not G.Model.CheckOverlap({ target(0, 0), target(0, 20) }))
    assert(G.Model.CheckOverlap({ target(0, 0), target(0, 40) }))
    assert(G.Model.CheckOverlap({ target(0, 0), target(100, 0) }))
end)
test("equal values in replaced objects do not confer ownership", function()
    local first, replacement = { size = 10 }, { size = 20 }
    local j = G.Journal.New(); j:Begin(); j:Write("a", first, "size", 20); j:Commit()
    assert(not j:Owns("a", { object = replacement, key = "size" }))
    j:Begin(); assert(not j:Write("a", replacement, "size", 30)); j:Rollback()
    assert(#j:Restore(function() return { object = replacement, key = "size" } end) == 1)
    assert(replacement.size == 20)
end)
test("unavailable resolver retains lease instead of using stale live table", function()
    local state = { size = 10 }; local j = G.Journal.New()
    j:Begin(); j:Write("a", state, "size", 20); j:Commit()
    local conflicts, pending = j:Restore(function() return nil end)
    assert(#conflicts == 0 and #pending == 1 and state.size == 20 and j.saved.a)
    j:Restore(function() return { object = state, key = "size" } end)
    assert(state.size == 10 and not j.saved.a)
end)
print("Unit tests passed: " .. passed)
